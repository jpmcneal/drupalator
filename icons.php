/**
 * Render a Lucide icon as inline SVG. $inline=true wraps it for alignment
 * next to body text; pass false for standalone placement (e.g. the header emblem).
 */
function getIcon(string $name, int $size = 16, bool $inline = true): string {
    $paths = DRUPALATOR_ICONS[$name] ?? '';
    $svg = "<svg xmlns='http://www.w3.org/2000/svg' width='{$size}' height='{$size}' viewBox='0 0 24 24' fill='none' stroke='currentColor' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>{$paths}</svg>";
    return $inline ? "<span class='icon-inline'>{$svg}</span>" : $svg;
}
